'use strict';
// Uses a fresh temporary browser context; no real user labels are created.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require(process.argv[2]);
async function main() {
  const project = path.resolve(__dirname, '..');
  const destination = fs.mkdtempSync(path.join(os.tmpdir(), 'robot-annotation-qa-'));
  const browser = await chromium.launch({headless: true, ...(process.argv[3] ? {executablePath: process.argv[3]} : {})});
  try {
    const context = await browser.newContext({viewport: {width: 1280, height: 1000}, acceptDownloads: true});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto(pathToFileURL(path.join(project, 'Annotation Review', 'pilot_annotation_review.html')).href);
    await page.waitForFunction(() => loadedFrameId === DATA.frames[0].id);
    assert.equal(await page.locator('#framePicker option').count(), 31);
    assert.equal(await page.locator('#metrics tr').count(), 0);
    const canvas = await page.locator('#imageCanvas').boundingBox();
    const pixel = (x,y) => ({x: canvas.x + canvas.width*x/640, y: canvas.y + canvas.height*y/480});
    const a = pixel(100,100), b = pixel(240,300);
    await page.mouse.move(a.x,a.y);await page.mouse.down();await page.mouse.move(b.x,b.y);await page.mouse.up();
    assert.equal(await page.evaluate(() => state().boxes.length), 1);
    assert.equal(await page.evaluate(() => state().reviewed), false);
    await page.locator('#occluded').check();
    assert.equal(await page.evaluate(() => state().boxes[0].occluded), true);
    await page.locator('#objectClass').selectOption('chair');
    await page.locator('#xmin').fill('110');
    await page.locator('#applyCoordinates').click();
    assert.equal(await page.evaluate(() => state().boxes[0].xmin), 110);
    await page.locator('#confirm').click();
    assert.equal(await page.evaluate(() => index), 1);
    assert.equal(await page.locator('#metrics tr').count(), 12);
    await page.locator('#suggestions').click();
    assert.ok(await page.evaluate(() => state().boxes.length) > 0);
    const before = await page.evaluate(() => state().boxes.length);
    await page.locator('#objects button').first().click();
    await page.locator('#deleteBox').click();
    assert.equal(await page.evaluate(() => state().boxes.length), before-1);
    await page.locator('#undo').click();
    assert.equal(await page.evaluate(() => state().boxes.length), before);
    await page.locator('#showPredictions').check();
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#exportLabels').click();
    const download = await downloadPromise;
    const exported = path.join(destination, 'simulated_qa_annotations.json');
    await download.saveAs(exported);
    const labels = JSON.parse(fs.readFileSync(exported,'utf8'));
    assert.equal(Object.values(labels.annotations).filter(value=>value.reviewed).length, 1);
    assert.equal(labels.frames.length, 31);
    assert.ok(!('image' in labels.frames[0]));
    await page.reload();
    await page.waitForFunction(() => loadedFrameId === frame().id);
    assert.equal(await page.evaluate(() => Object.values(states).filter(value=>value.reviewed).length),1);
    await page.locator('#importLabels').setInputFiles(exported);
    await page.waitForFunction(() => document.getElementById('message').textContent === 'Saved annotations loaded.');
    await page.locator('#framePicker').selectOption('30');
    await page.waitForFunction(() => loadedFrameId === frame().id);
    assert.equal(await page.evaluate(() => frame().cohort), 'challenge');
    assert.ok(await page.evaluate(() => frame().id.includes('0030_raw')));
    await page.screenshot({path:path.join(destination,'desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(destination,'mobile.png'),fullPage:true});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'passed', checks:['31 images','draft excluded','draw box','occlusion flag','coordinate edit','confirm and score','suggestions','delete and undo','export','browser reload','import','challenge isolation','mobile width','no page errors'], qa_folder:destination}));
  } finally { await browser.close(); }
}
main().catch(error => {console.error(error);process.exitCode=1;});
